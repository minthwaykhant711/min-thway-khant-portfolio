(() => {
  const header = document.querySelector('.site-header');
  const menuButton = document.querySelector('.menu-btn');
  const navigation = document.querySelector('.nav-links');
  const mobileQuery = matchMedia('(max-width: 900px)');
  const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');

  function closeNavigation(restoreFocus = false) {
    const wasOpen = navigation.classList.contains('open');
    navigation.classList.remove('open');
    menuButton.setAttribute('aria-expanded', 'false');
    menuButton.setAttribute('aria-label', 'Open navigation');
    if (restoreFocus && wasOpen) menuButton.focus();
  }

  menuButton.addEventListener('click', () => {
    const open = navigation.classList.toggle('open');
    menuButton.setAttribute('aria-expanded', String(open));
    menuButton.setAttribute('aria-label', open ? 'Close navigation' : 'Open navigation');
  });
  navigation.addEventListener('click', event => {
    const link = event.target.closest('a');
    if (!link) return;
    closeNavigation();
    // A hidden mobile-menu link must not retain keyboard focus.
    if (mobileQuery.matches && link.hash && link.origin === location.origin) {
      const target = document.getElementById(link.hash.slice(1));
      if (target) {
        if (!target.hasAttribute('tabindex')) target.setAttribute('tabindex', '-1');
        target.focus({ preventScroll: true });
      }
    }
  });
  header.querySelector('.brand').addEventListener('click', () => closeNavigation());
  document.addEventListener('click', event => {
    if (!header.contains(event.target)) closeNavigation();
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape') closeNavigation(true);
  });
  header.addEventListener('focusout', event => {
    if (!header.contains(event.relatedTarget)) closeNavigation();
  });
  mobileQuery.addEventListener('change', () => closeNavigation());
  menuButton.hidden = false;
  header.classList.add('navigation-ready');

  // Theme is applied in the head to avoid a flash. Storage is optional.
  const themeButton = document.querySelector('.theme-toggle');
  const systemTheme = matchMedia('(prefers-color-scheme: dark)');
  let explicitTheme = false;
  try { explicitTheme = ['light', 'dark'].includes(localStorage.getItem('portfolio-theme')); } catch { /* Browser storage is optional. */ }
  function setTheme(theme) {
    const dark = theme === 'dark';
    document.documentElement.dataset.theme = theme;
    document.querySelector('meta[name="theme-color"]').content = dark ? '#101c20' : '#f7f8f5';
    themeButton.setAttribute('aria-label', 'Dark theme');
    themeButton.setAttribute('aria-pressed', String(dark));
    themeButton.title = dark ? 'Switch to light theme' : 'Switch to dark theme';
    themeButton.querySelector('.theme-label').textContent = dark ? 'Dark' : 'Light';
  }
  setTheme(document.documentElement.dataset.theme || 'light');
  themeButton.addEventListener('click', () => {
    const next = document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark';
    explicitTheme = true;
    setTheme(next);
    try { localStorage.setItem('portfolio-theme', next); } catch { /* Keep the in-session preference. */ }
  });
  systemTheme.addEventListener('change', event => {
    if (!explicitTheme) setTheme(event.matches ? 'dark' : 'light');
  });
  themeButton.hidden = false;

  // Filters enhance the existing HTML; all cards remain readable without JS.
  const projectCards = [...document.querySelectorAll('#project-grid > [data-project]')];
  const filterButtons = [...document.querySelectorAll('[data-filter]')];
  const filterCount = document.getElementById('filter-count');
  filterButtons.forEach(button => {
    button.addEventListener('click', () => {
      const category = button.dataset.filter;
      let visible = 0;
      projectCards.forEach(card => {
        const match = category === 'all' || card.dataset.categories.split(' ').includes(category);
        card.hidden = !match;
        if (match) {
          visible++;
          card.classList.remove('reveal-pending');
          card.classList.add('reveal-visible');
        }
      });
      filterButtons.forEach(other => other.setAttribute('aria-pressed', String(other === button)));
      filterCount.textContent = category === 'all'
        ? 'Showing all ' + visible + ' projects'
        : 'Showing ' + visible + ' ' + (visible === 1 ? 'project' : 'projects') + ' · ' + button.textContent.trim();
    });
  });
  document.querySelector('.filter-toolbar').hidden = false;

  // Evidence links should also work when their project was filtered out.
  document.addEventListener('click', event => {
    const anchor = event.target.closest('a[href^="#project-"]');
    if (!anchor || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    const target = document.getElementById(anchor.hash.slice(1));
    if (target?.hidden) document.querySelector('[data-filter="all"]').click();
  });

  // Native modal dialog supplies focus containment and an inert background.
  const modal = document.getElementById('projectModal');
  const image = document.getElementById('modalImage');
  const video = document.getElementById('modalVideo');
  const status = document.getElementById('mediaStatus');
  const counter = document.getElementById('modalCounter');
  const caption = document.getElementById('mediaCaption');
  const original = document.getElementById('originalMedia');
  let currentProject = null;
  let currentIndex = 0;
  let returnFocus = null;
  let previousOverflow = '';
  let mediaRequest = 0;

  function clearVideo() {
    if (!video.hasAttribute('src')) return;
    video.pause();
    video.removeAttribute('src');
    video.load();
  }

  function showMedia() {
    const media = galleryMedia[currentProject][currentIndex];
    const request = ++mediaRequest;
    const isVideo = media.type === 'video';
    clearVideo();
    image.hidden = true;
    video.hidden = true;
    status.textContent = 'Loading ' + (isVideo ? 'video' : 'image') + '…';
    counter.textContent = (currentIndex + 1) + ' / ' + galleryMedia[currentProject].length;
    caption.textContent = media.caption;
    original.href = media.original;
    const loaded = () => {
      if (request !== mediaRequest) return;
      status.textContent = '';
    };
    const failed = () => {
      if (request !== mediaRequest) return;
      status.textContent = 'Unable to load this media. Use “Open original media” below.';
    };
    if (isVideo) {
      video.onloadeddata = loaded;
      video.onerror = failed;
      video.setAttribute('aria-label', media.caption);
      video.src = media.src;
      video.hidden = false;
      video.load();
    } else {
      image.onload = loaded;
      image.onerror = failed;
      image.alt = document.getElementById('modalTitle').textContent + ' — ' + media.caption;
      image.sizes = '(max-width: 900px) calc(100vw - 72px), 700px';
      if (media.srcset) image.srcset = media.srcset;
      else image.removeAttribute('srcset');
      image.src = media.src;
      image.hidden = false;
    }
  }

  function openGallery(key, trigger) {
    const card = document.querySelector('[data-project="' + key + '"]');
    if (!card || !galleryMedia[key]?.length || typeof modal.showModal !== 'function') return false;
    closeNavigation();
    currentProject = key;
    currentIndex = 0;
    returnFocus = trigger;
    document.getElementById('modalTitle').textContent = card.querySelector('h3').textContent;
    document.getElementById('modalKicker').textContent = card.querySelector('.project-kicker').textContent;
    document.getElementById('modalDescription').textContent = card.querySelector('.project-summary').textContent;
    document.getElementById('modalRole').textContent = 'MY ROLE · ' + card.querySelector('.project-role strong').textContent;
    const details = card.querySelector('.case-study-body');
    const caseStudy = document.getElementById('modalCaseStudy');
    caseStudy.replaceChildren();
    if (details) {
      const copy = details.cloneNode(true);
      copy.querySelectorAll('h4').forEach(heading => {
        const replacement = document.createElement('h3');
        replacement.textContent = heading.textContent;
        heading.replaceWith(replacement);
      });
      caseStudy.append(copy);
    }
    previousOverflow = document.body.style.overflow;
    modal.showModal();
    document.body.style.overflow = 'hidden';
    showMedia();
    return true;
  }

  document.addEventListener('click', event => {
    const trigger = event.target.closest('[data-open-gallery]');
    if (!trigger || event.defaultPrevented || event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    if (openGallery(trigger.dataset.openGallery, trigger)) event.preventDefault();
  });
  modal.querySelector('.modal-close').addEventListener('click', () => modal.close());
  modal.addEventListener('close', () => {
    mediaRequest++;
    clearVideo();
    image.removeAttribute('src');
    image.removeAttribute('srcset');
    image.hidden = true;
    video.hidden = true;
    status.textContent = '';
    currentProject = null;
    document.body.style.overflow = previousOverflow;
    if (returnFocus?.isConnected) returnFocus.focus({ preventScroll: true });
  });
  // Close only when the click is outside the dialog's border box.
  let backdropPress = false;
  function outsideDialog(event) {
    const box = modal.getBoundingClientRect();
    return event.clientX < box.left || event.clientX > box.right || event.clientY < box.top || event.clientY > box.bottom;
  }
  modal.addEventListener('pointerdown', event => { backdropPress = event.target === modal && outsideDialog(event); });
  modal.addEventListener('click', event => {
    if (backdropPress && event.target === modal && outsideDialog(event)) modal.close();
    backdropPress = false;
  });
  function moveMedia(step) {
    if (!currentProject) return;
    const total = galleryMedia[currentProject].length;
    currentIndex = (currentIndex + step + total) % total;
    showMedia();
  }
  modal.querySelector('.gallery-prev').addEventListener('click', () => moveMedia(-1));
  modal.querySelector('.gallery-next').addEventListener('click', () => moveMedia(1));
  modal.addEventListener('keydown', event => {
    if (event.key === 'Tab') {
      // Explicitly wrap the ends; native dialogs can otherwise send focus to
      // browser chrome. Leave the video's internal controls to the browser.
      const focusable = [...modal.querySelectorAll('button:not([disabled]), a[href], video[controls]')]
        .filter(element => element.getClientRects().length > 0 && !element.hidden);
      const first = focusable[0];
      const last = focusable.at(-1);
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
      return;
    }
    if (event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
    if (event.target.closest('video, input, textarea, select, [contenteditable]')) return;
    if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
      event.preventDefault();
      moveMedia(event.key === 'ArrowLeft' ? -1 : 1);
    }
  });

  // Copying is optional; a readable mailto link is always present.
  const copyButton = document.querySelector('.copy-email');
  const copyStatus = document.querySelector('.copy-status');
  const emailLink = document.getElementById('email-link');
  copyButton.addEventListener('click', async () => {
    try {
      if (!navigator.clipboard?.writeText) throw new Error('Clipboard unavailable');
      await navigator.clipboard.writeText(emailLink.href.replace('mailto:', ''));
      copyStatus.textContent = 'Email address copied.';
    } catch {
      const range = document.createRange();
      range.selectNodeContents(emailLink.querySelector('.email-address'));
      const selection = window.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
      copyStatus.textContent = 'Select and copy the email address, or use the email link.';
    }
  });
  copyButton.hidden = false;

  if ('IntersectionObserver' in window) {
    const revealed = [...document.querySelectorAll('.project-card, .skill-group, .experience-card, .credential, .journey-entry')];
    if (!reducedMotion.matches) {
      const observer = new IntersectionObserver(entries => {
        entries.forEach(entry => {
          if (!entry.isIntersecting) return;
          entry.target.classList.remove('reveal-pending');
          entry.target.classList.add('reveal-visible');
          observer.unobserve(entry.target);
        });
      }, { threshold: .06 });
      revealed.forEach(element => {
        element.classList.add('reveal-pending');
        observer.observe(element);
      });
      reducedMotion.addEventListener('change', event => {
        if (!event.matches) return;
        observer.disconnect();
        revealed.forEach(element => element.classList.remove('reveal-pending'));
      });
    }
    const navAnchors = [...navigation.querySelectorAll('a[href^="#"]')];
    const sections = navAnchors.map(anchor => document.querySelector(anchor.hash));
    const sectionObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        navAnchors.forEach(anchor => {
          if (anchor.hash === '#' + entry.target.id) anchor.setAttribute('aria-current', 'location');
          else anchor.removeAttribute('aria-current');
        });
      });
    }, { rootMargin: '-10% 0px -65% 0px', threshold: 0 });
    sections.forEach(section => { if (section) sectionObserver.observe(section); });
  }
})();
